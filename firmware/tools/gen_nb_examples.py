#!/usr/bin/env python3
"""The example notebooks shipped with the Python module (notebooks/*.ipynb).

    gen_nb_examples.py --c-out modules/python/nb_examples.c   embed the notebooks as C strings
    gen_nb_examples.py --check modules/python/nb_examples.c   fail if that file is out of date
    gen_nb_examples.py --refresh --sim build/sim/calcsim      run every example on the calculator
                                                               and store its outputs (make nb-examples)

The notebooks in firmware/notebooks/ are ordinary nbformat 4.5 files as the calculator writes
them (docs/NOTEBOOK.md, "The .ipynb mapping"), with their outputs, so they open with results in
the calculator's MENU > Open list, in Jupyter and on GitHub. They are written by the calculator
itself: --refresh drops each one on the simulator's CALC drive (the import of a .ipynb), opens
it, clears the outputs, runs all cells, saves it and copies it back off the drive, so the outputs
(math results with their LaTeX, graph pictures) are exactly the calculator's. A cell that ends
in an error fails the refresh. Edit a notebook on the calculator, in the browser page or in
Jupyter (math cells keep `metadata.calculator.input`), then run `make nb-examples`.

The Python module (modules/python/nb_examples.c, checked in) holds the files as they are:
nb_list_all() lists them after the user's notebooks and nb_load() reads one like a stored
notebook, which is saved to the notebook store under its name at the first change
(modules/python/nb_doc.c). `make test` runs --check (nb-examples-check), so the C file cannot
fall behind the notebooks.
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.normpath(os.path.join(HERE, ".."))
NB_DIR = os.path.join(FW, "notebooks")
sys.path.insert(0, HERE)


def notebooks():
    """[(name, path)] of notebooks/*.ipynb, sorted by name (the order of the list on the calculator)."""
    return [(os.path.basename(p)[:-6], p) for p in sorted(glob.glob(os.path.join(NB_DIR, "*.ipynb")))]


def c_source():
    """The C file: one string per notebook (its bytes, UTF-8) and the table nb_examples[]."""
    o = ["/* Generated by tools/gen_nb_examples.py from the .ipynb files in firmware/notebooks. Do not edit:",
         " * change the notebooks and run `make nb-examples` (docs/NOTEBOOK.md, \"Example notebooks\"). */",
         '#include "nb.h"', ""]
    rows = []
    for k, (name, path) in enumerate(notebooks()):
        data = open(path, "rb").read()
        if len(name.encode()) >= 36:
            raise SystemExit(f"{path}: the name is longer than 35 bytes")
        o.append(f"static const char ex{k}[] =")
        for i in range(0, len(data), 64):
            piece = data[i:i + 64]
            o.append('    "' + "".join(c_char(b) for b in piece) + '"')
        o[-1] += ";"
        rows.append(f'    {{"{name}", ex{k}, {len(data)}}},')
    o += ["", f"const nb_example_t nb_examples[{max(len(rows), 1)}] = {{"] + (rows or ['    {"", "", 0},']) + ["};",
          f"const int nb_nexamples = {len(rows)};", ""]
    return "\n".join(o)


def c_char(b):
    """One byte as it goes into a C string literal (octal escapes for anything not plain ASCII,
    always three digits, so a following digit cannot join the escape)."""
    c = chr(b)
    if c in '"\\':
        return "\\" + c
    if 32 <= b < 127 and c != "?":  # (no "??" trigraphs)
        return c
    return f"\\{b:03o}"


def refresh(sim):
    """Run every notebook on the simulator and write it back with the calculator's outputs."""
    import release_version
    ver = release_version.fmt(release_version.release_version())
    with tempfile.TemporaryDirectory(prefix="nbex-") as tmp:
        # (the advanced CAS module, as in help-test: from the simulated card when not built in)
        lines = ["ifcfg CONTENT_QSPI ifcfg !MOD_CASX fs insert 64", "ifcfg CONTENT_QSPI ifcfg !MOD_CASX fs format",
                 "ifcfg CONTENT_QSPI ifcfg !MOD_CASX module library",
                 "ifcfg CONTENT_QSPI ifcfg !MOD_CASX module installall", "nb store wipe", "usb host on"]
        for name, path in notebooks():
            lines += [f'usb drop "{path}" mac', "wait 1000", f'nb open "{name}"', "nb clear", "nb runall",
                      "nb close"]
        lines += ["usb host off", "usb host on"]
        for name, _ in notebooks():
            lines.append(f'usb get "NOTEBOOKS/{name}.ipynb" "{os.path.join(tmp, name)}.ipynb"')
        script = os.path.join(tmp, "refresh.txt")
        open(script, "w").write("\n".join(lines) + "\n")
        r = subprocess.run([sim, "--script", script, "--shots", tmp], capture_output=True, text=True,
                           errors="replace", timeout=600)
        errs = [l for l in r.stdout.splitlines() if l.startswith("ERR")]
        if r.returncode or errs:
            raise SystemExit("gen_nb_examples: the simulator failed:\n" + "\n".join(errs) + r.stderr[-2000:])
        for name, path in notebooks():
            nb = json.load(open(os.path.join(tmp, name + ".ipynb"), encoding="utf-8"))
            for c in nb["cells"]:
                for out in c.get("outputs", []):
                    if out.get("output_type") == "error":
                        src = c.get("metadata", {}).get("calculator", {}).get("input") or "".join(c["source"])
                        raise SystemExit(f"{name}: the cell {src!r} gives {out.get('evalue')}")
            # the version that wrote it: the release, not this build's +N-gHASH
            nb.setdefault("metadata", {}).setdefault("calculator", {})["firmware"] = ver
            with open(path, "w", encoding="utf-8") as f:
                json.dump(nb, f, indent=1, ensure_ascii=False, sort_keys=True)
                f.write("\n")
            print(f"{name}: {len(nb['cells'])} cells")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--c-out")
    ap.add_argument("--check")
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--sim")
    a = ap.parse_args()
    if a.refresh:
        if not a.sim:
            ap.error("--refresh needs --sim")
        refresh(a.sim)
    if a.c_out:
        with open(a.c_out, "w", encoding="utf-8") as f:
            f.write(c_source())
    if a.check:
        if not os.path.exists(a.check) or open(a.check, encoding="utf-8").read() != c_source():
            print(f"{a.check} is out of date: run `make nb-examples-c` (tools/gen_nb_examples.py --c-out)")
            return 1
        print(f"{a.check}: {len(notebooks())} example notebooks, up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
