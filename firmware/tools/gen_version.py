#!/usr/bin/env python3
"""Write the build's version source (core/version.h): the version string and the moment of the link.

    gen_version.py --version STRING --out DIR/version.c

The Makefile runs this in every link rule (firmware, bring-up image, simulator, tests, web
pages), with the version object depending on every other object of that link and on a stamp of
the version string (tools/release_version.py describe), so the `version` command, About and
INFO.TXT always name the build that is running. The arrays have fixed sizes: a new version string
moves nothing else in the image (make release compares images with these bytes masked out).
"""
import argparse
import os
import time


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    now = time.localtime(int(os.environ.get("SOURCE_DATE_EPOCH", time.time())))
    v = a.version[:47].replace("\\", "").replace('"', "")
    text = ("/* generated by tools/gen_version.py at link time: do not edit */\n"
            '#include "version.h"\n'
            f'const char fw_version[48] = "{v}";\n'
            f'const char fw_build_date[12] = "{time.strftime("%b %e %Y", now)}";\n'
            f'const char fw_build_time[12] = "{time.strftime("%H:%M:%S", now)}";\n')
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
