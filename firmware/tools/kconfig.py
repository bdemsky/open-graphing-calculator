#!/usr/bin/env python3
"""Kconfig front end for the firmware build (vendored kconfiglib, third_party/kconfiglib).

    kconfig.py sync --config BUILD/.config --gen-dir BUILD/gen
                    [--defconfig configs/X_defconfig] [--force] [--set SYM=VALUE ...]
    kconfig.py menuconfig --config BUILD/.config
    kconfig.py savedefconfig --config BUILD/.config --out FILE
    kconfig.py check configs/*_defconfig

sync (run by the Makefile on every invocation): loads BUILD/.config, or the
defconfig when the .config does not exist yet or --force is given (make
TIER=x), applies --set overrides (command-line CAS=, CONTENT=, MANUAL=),
and writes, each only if its contents changed (so make rebuilds only on a
real change):
    BUILD/.config              included by the Makefile (CONFIG_x=y lines)
    BUILD/gen/autoconf.h       #define CONFIG_x for C (-include'd everywhere)
    BUILD/gen/config_gen.c     build_config[]: names of the enabled bool options
                               and the tier, for MEM > About and console `ifcfg`
check: every defconfig must load without warnings (unknown or unsettable
symbols, i.e. a defconfig that rotted after a Kconfig change).
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(FW, "third_party", "kconfiglib"))
import kconfiglib  # noqa: E402


def load(kconfig):
    kc = kconfiglib.Kconfig(kconfig, warn_to_stderr=False)
    kc.warn_assign_undef = True
    kc.warn_assign_override = False
    kc.warn_assign_redun = False
    return kc


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    try:
        if open(path, encoding="utf-8").read() == text:
            return
    except OSError:
        pass
    with open(path + ".tmp", "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(path + ".tmp", path)


def tier(kc):
    if kc.syms["CONTENT_INTERNAL"].str_value == "y":
        return "core"
    return "advanced" if kc.syms["CAS_EXT"].str_value == "y" else "standard"


def config_c(kc):
    on = [s.name for s in kc.unique_defined_syms if s.type == kconfiglib.BOOL and s.str_value == "y"]
    lines = ["/* Generated by tools/kconfig.py from the build's .config. Do not edit. */",
             "#include <stddef.h>",
             f'const char *const build_tier = "{tier(kc)}";',
             "const char *const build_config[] = {"]
    lines += [f'    "{n}",' for n in on] + ["    NULL,", "};", ""]
    return "\n".join(lines)


def sync(a):
    kc = load(os.path.join(FW, "Kconfig"))
    if a.force or not os.path.exists(a.config):
        if not a.defconfig or not os.path.exists(a.defconfig):
            print(f"kconfig: no {a.config} and no defconfig {a.defconfig!r}", file=sys.stderr)
            return 1
        kc.load_config(a.defconfig)
    else:
        kc.load_config(a.config)
    for s in a.set:
        name, _, val = s.partition("=")
        if name.startswith("CONFIG_"):
            name = name[7:]
        sym = kc.syms.get(name)
        if sym is None or not sym.set_value(val):
            print(f"kconfig: cannot set {name}={val}", file=sys.stderr)
            return 1
        if sym.str_value != val:
            print(f"kconfig: {name}={val} is not possible here (dependencies: "
                  f"{kconfiglib.expr_str(sym.direct_dep)}); it is {sym.str_value!r}", file=sys.stderr)
            return 1
    for w in kc.warnings:
        print("kconfig: " + w, file=sys.stderr)
    os.makedirs(os.path.dirname(os.path.abspath(a.config)), exist_ok=True)
    os.makedirs(a.gen_dir, exist_ok=True)
    # both leave an unchanged file untouched (timestamps stay, nothing rebuilds)
    kc.write_config(a.config, header="# Generated by tools/kconfig.py (make menuconfig to edit)\n",
                    save_old=False)
    kc.write_autoconf(os.path.join(a.gen_dir, "autoconf.h"),
                      header="/* Generated by tools/kconfig.py from the build's .config. Do not edit. */\n")
    write_if_changed(os.path.join(a.gen_dir, "config_gen.c"), config_c(kc))
    return 0


def check(a):
    bad = 0
    for path in a.defconfigs:
        kc = load(os.path.join(FW, "Kconfig"))
        kc.load_config(path)
        ws = [w for w in kc.warnings]
        # every symbol the defconfig sets must end up with that value
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line.startswith("CONFIG_") and "=" in line:
                name, val = line[7:].split("=", 1)
                sym = kc.syms.get(name)
                val = val.strip('"')
                if sym is None:
                    ws.append(f"unknown symbol {name}")
                elif sym.str_value != val:
                    ws.append(f"{name}={val} does not stick (is {sym.str_value!r}; depends on "
                              f"{kconfiglib.expr_str(sym.direct_dep)})")
        print(f"{path}: {'ok' if not ws else 'FAILED'} (tier {tier(kc)})")
        for w in ws:
            print("    " + w)
        bad += bool(ws)
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sync")
    s.add_argument("--config", required=True)
    s.add_argument("--gen-dir", required=True)
    s.add_argument("--defconfig")
    s.add_argument("--force", action="store_true")
    s.add_argument("--set", action="append", default=[])
    m = sub.add_parser("menuconfig")
    m.add_argument("--config", required=True)
    d = sub.add_parser("savedefconfig")
    d.add_argument("--config", required=True)
    d.add_argument("--out", required=True)
    c = sub.add_parser("check")
    c.add_argument("defconfigs", nargs="+")
    a = ap.parse_args()
    if a.cmd == "sync":
        return sync(a)
    if a.cmd == "check":
        return check(a)
    if a.cmd == "savedefconfig":
        kc = load(os.path.join(FW, "Kconfig"))
        kc.load_config(a.config)
        kc.write_min_config(a.out)
        print(f"kconfig: minimal configuration written to {a.out}")
        return 0
    os.environ["KCONFIG_CONFIG"] = a.config
    import menuconfig
    menuconfig.menuconfig(load(os.path.join(FW, "Kconfig")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
