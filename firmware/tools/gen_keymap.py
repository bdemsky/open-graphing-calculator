#!/usr/bin/env python3
"""Generate core/gen/keymap_gen.{h,c}.

Inputs:
  keys/layout.py                 the logical layout (names, legends, texts, SHIFT/ALPHA layers)
  ../hardware/gen/design.py      LAYOUT: the keys in PCB order, wired row-major into the 7x7 matrix
  ../hardware/pinmap/pinmap.py   KEY_ROWS / KEY_COLS: the matrix pins
design.py and pinmap.py are parsed with `ast` (not imported), so this script
has no dependency on the KiCad generator.

Usage: gen_keymap.py OUTDIR

How a key code is assigned: design.py LAYOUT lists the 49 matrix keys by name
(the key switch values in the schematic) in seven rows of seven, and the
schematic generator wires LAYOUT[r][c] to matrix row r, column c. Key codes are 1..49 in matrix order (row-major), then ON (50, wired to
PA0/WKUP1 outside the matrix so it can wake the MCU from Standby); 0 is
KEY_NONE. Moving a logical key on the PCB therefore changes key codes but no
firmware source, since code refers to keys by enum name.

Generated tables: key_matrix (row, col -> code; used by the keypad scanner),
key_pos (code -> row << 4 | col; to map codes to hal_keypad_raw() bits),
key_names and key_aliases (console `key`/`keys` commands, web API), key_info
(legends, typed text and actions per layer for app/keys.c), and the matrix
GPIO pins as KEY_ROW_*/KEY_COL_* macros (not used by the firmware sources,
which take the pins from board.h; tools/check_pins.py checks both agree).

Consistency checks (abort the build on failure): layout.check() against
LAYOUT, 49 unique switches, a 7x7 pin set, F1..F5 consecutive (KEY_IS_SOFT
relies on it), and every action name present in app/keys.c actions[].
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DESIGN = os.path.join(HERE, "../../hardware/gen/design.py")
PINMAP = os.path.join(HERE, "../../hardware/pinmap/pinmap.py")
sys.path.insert(0, os.path.join(HERE, "../keys"))
import layout  # noqa: E402


def find_assign(path, name):
    """Value of the first `name = <literal>` assignment anywhere in a Python
    file, evaluated with ast.literal_eval (the file is never executed)."""
    tree = ast.parse(open(path).read(), path)
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in {path}")


def ident(k):
    """C enum name of logical key k."""
    return "KEY_" + k


def cstr(s):
    """C string literal for s (backslash and quote escaped; UTF-8 kept as is),
    or NULL for None."""
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    """Write keymap_gen.h and keymap_gen.c into OUTDIR (argv[1])."""
    outdir = sys.argv[1]
    design_layout = find_assign(DESIGN, "LAYOUT")
    rows = find_assign(PINMAP, "KEY_ROWS")
    cols = find_assign(PINMAP, "KEY_COLS")
    layout.check(design_layout)
    keys = [k for row in design_layout for k in row]          # matrix order
    assert len(keys) == 49 and len(set(keys)) == 49, "expected 49 unique keys"
    assert len(rows) == 7 and len(cols) == 7
    pos = {k: (i // 7, i % 7) for i, k in enumerate(keys)}    # same rule as design.py KEYMAP
    allkeys = keys + ["ON"]
    info = {k: layout.BY_NAME[k] for k in allkeys}
    # every action named in layout.py must exist in app/keys.c actions[]
    import re
    known = set(re.findall(r'\{"([a-z]+)", [a-z_]+\}', open(os.path.join(HERE, "../app/keys.c")).read()))
    for k in allkeys:
        for a in (info[k]["action"], info[k]["shift_action"]):
            assert a is None or a in known, f"{k}: action {a!r} is not in app/keys.c actions[]"

    h = ["/* Generated by tools/gen_keymap.py from keys/layout.py (logical layout),",
         " * hardware/gen/design.py (LAYOUT: PCB key order, matrix wiring) and",
         " * hardware/pinmap/pinmap.py (KEY_ROWS/KEY_COLS). Do not edit. */",
         "#ifndef KEYMAP_GEN_H", "#define KEYMAP_GEN_H", "#include <stdint.h>", "",
         "#define KEYPAD_ROWS 7", "#define KEYPAD_COLS 7", "", "enum key_code {", "    KEY_NONE = 0,"]
    for i, k in enumerate(allkeys, 1):
        r, c = pos.get(k, (None, None))
        where = f"row {r} col {c}" if r is not None else "PA0/WKUP1, not in matrix"
        h.append(f"    {ident(k)} = {i},  /* {where}: {info[k]['legend']} */")
    h.append(f"    KEY_COUNT = {len(allkeys) + 1}")
    h.append("};")
    h += ["", "#define KEY_IS_SOFT(k) ((k) >= KEY_F1 && (k) <= KEY_F5)",
          "#define KEY_SOFT_INDEX(k) ((k) - KEY_F1)", ""]
    assert [allkeys.index(f"F{i}") for i in range(1, 6)] == list(range(allkeys.index("F1"), allkeys.index("F1") + 5))
    h += ["/* key_matrix[row][col] -> key code */",
          "extern const uint8_t key_matrix[KEYPAD_ROWS][KEYPAD_COLS];",
          "/* key code -> (row << 4 | col), 0xFF if not in the matrix */",
          "extern const uint8_t key_pos[KEY_COUNT];",
          "/* key code -> canonical name (keys/layout.py) */",
          "extern const char *const key_names[KEY_COUNT];",
          "/* alias table for the console: {alias, key} pairs, NULL-terminated */",
          "typedef struct { const char *alias; uint8_t key; } key_alias_t;",
          "extern const key_alias_t key_aliases[];",
          "",
          "/* What each key is (keys/layout.py): legends, the text it types, global",
          " * actions (app/keys.c), per layer. NULL: nothing in that layer. */",
          "typedef struct {",
          "    const char *legend;                   /* keycap */",
          "    const char *text, *suffix;            /* plain: inserted before / after the cursor */",
          "    const char *action;                   /* plain: global action (app/keys.c) */",
          "    const char *shift;                    /* SHIFT legend */",
          "    const char *shift_text, *shift_suffix;",
          "    const char *shift_action;",
          "    const char *alpha;                    /* ALPHA character (UTF-8, lower case) */",
          "} key_info_t;",
          "extern const key_info_t key_info[KEY_COUNT];",
          "",
          # pinmap.py names pins "PD10" etc.: p[1] is the port letter, p[2:] the number
          "/* Matrix pins (port letter, pin number), rows open-drain outputs, columns pull-up inputs */",
          "#define KEY_ROW_PORTS {" + ", ".join(f"'{p[1]}'" for p in rows) + "}",
          "#define KEY_ROW_PINS  {" + ", ".join(p[2:] for p in rows) + "}",
          "#define KEY_COL_PORTS {" + ", ".join(f"'{p[1]}'" for p in cols) + "}",
          "#define KEY_COL_PINS  {" + ", ".join(p[2:] for p in cols) + "}",
          "",
          "#endif"]

    c = ["/* Generated by tools/gen_keymap.py from keys/layout.py. Do not edit. */", '#include "keymap_gen.h"',
         '#include <stddef.h>', "", "const uint8_t key_matrix[KEYPAD_ROWS][KEYPAD_COLS] = {"]
    for r in range(7):
        c.append("    {" + ", ".join(ident(keys[r * 7 + cc]) for cc in range(7)) + "},")
    c += ["};", "", "const uint8_t key_pos[KEY_COUNT] = {", "    0xFF,"]
    for k in allkeys:
        if k in pos:
            r, cc = pos[k]
            c.append(f"    0x{r:X}{cc:X},  /* {k} */")
        else:
            c.append(f"    0xFF,  /* {k} */")
    c += ["};", "", "const char *const key_names[KEY_COUNT] = {", '    "NONE",']
    for k in allkeys:
        c.append(f'    "{k}",')
    c += ["};", "", "const key_alias_t key_aliases[] = {"]
    # aliases are case-insensitive; one equal to a key name or to an earlier
    # alias is dropped (first one wins)
    seen = {k.upper() for k in allkeys}
    for k in allkeys:
        for a in info[k]["aliases"]:
            if a.upper() in seen:
                continue
            seen.add(a.upper())
            c.append(f'    {{{cstr(a)}, {ident(k)}}},')
    c += ["    {0, 0}", "};", "", "const key_info_t key_info[KEY_COUNT] = {", "    {0},"]
    for k in allkeys:
        d = info[k]
        f = [d["legend"], d["text"], d["suffix"], d["action"], d["shift"], d["shift_text"], d["shift_suffix"],
             d["shift_action"], d["alpha"]]
        c.append(f"    {{{', '.join(cstr(x) for x in f)}}}, /* {k} */")
    c.append("};")

    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "keymap_gen.h"), "w") as fh:
        fh.write("\n".join(h) + "\n")
    with open(os.path.join(outdir, "keymap_gen.c"), "w") as fh:
        fh.write("\n".join(c) + "\n")


if __name__ == "__main__":
    main()
