#!/usr/bin/env python3
"""Generate MicroPython's headers for the calculator's Python module.

    py_genhdr.py --cc clang --top third_party/micropython --out build/gen/mpy \
                 --flags "-I... -D..." SRC.c ...

MicroPython builds tables of interned strings (qstrs), built-in modules and
root pointers from the sources that use them (MP_QSTR_xxx, MP_REGISTER_MODULE,
MP_REGISTER_ROOT_POINTER). Upstream does this with py/mkrules.mk; this script
runs the same steps with the upstream scripts (py/makeqstrdefs.py,
makeqstrdata.py, makemoduledefs.py, make_root_pointers.py):

  1. preprocess every source with -DNO_QSTR (host compiler, at most 8 at a
     time) and keep the lines with MP_QSTR / MP_REGISTER / MP_COMPRESSED;
  2. split and collect the qstrs, modules and root pointers;
  3. preprocess qstrdefs.h + the collected qstrs and run makeqstrdata.py;
  4. write genhdr/{qstrdefs.generated.h, moduledefs.h, root_pointers.h,
     mpversion.h} -- only when their contents changed, so an unchanged
     run rebuilds nothing.

One set of headers serves the simulators and the firmware image (the same
mpconfigport.h; nothing in it depends on the target).
"""
import argparse
import concurrent.futures
import os
import re
import shlex
import subprocess
import sys

VERSION = "v1.29.0"  # third_party/README.md; also MICROPY_VERSION in py/mpconfig.h
RE_LINE = re.compile(rb"^#(?:line)?\s+\d+\s\"")
RE_INFO = re.compile(rb"MP_COMP|MP_QSTR|MP_REGI|micropy_hw")


def pp(cc, flags, src):
    out = subprocess.run([cc, "-E", "-DNO_QSTR"] + flags + [src], capture_output=True)
    if out.returncode:
        sys.stderr.write(out.stderr.decode(errors="replace"))
        raise SystemExit(f"py_genhdr: preprocessing {src} failed")
    keep, recent = [], None
    for line in out.stdout.splitlines(keepends=True):
        if line.isspace():
            continue
        if RE_LINE.match(line):
            recent = line
        elif RE_INFO.search(line):
            if recent:
                keep.append(recent)
                recent = None
            keep.append(line)
    return b"".join(keep)


def write_if_changed(path, data):
    if os.path.exists(path) and open(path, "rb").read() == data:
        return
    with open(path, "wb") as f:
        f.write(data)


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, **kw)
    if r.returncode:
        sys.stderr.write(r.stderr.decode(errors="replace"))
        raise SystemExit("py_genhdr: failed: " + " ".join(cmd))
    return r.stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cc", required=True)
    ap.add_argument("--top", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--flags", default="")
    ap.add_argument("srcs", nargs="+")
    a = ap.parse_args()
    flags = shlex.split(a.flags)
    py = os.path.join(a.top, "py")
    tmp = os.path.join(a.out, "tmp")
    gen = os.path.join(a.out, "genhdr")
    os.makedirs(tmp, exist_ok=True)
    os.makedirs(gen, exist_ok=True)
    # mpversion.h first: the sources include it while being preprocessed
    write_if_changed(os.path.join(gen, "mpversion.h"),
                     (f'// generated by tools/py_genhdr.py\n#define MICROPY_GIT_TAG "{VERSION}"\n'
                      f'#define MICROPY_GIT_HASH "{VERSION}"\n#define MICROPY_BUILD_DATE "{VERSION}"\n').encode())
    for name in ("qstrdefs.generated.h", "moduledefs.h", "root_pointers.h"):
        p = os.path.join(gen, name)
        if not os.path.exists(p):  # placeholders so that the first preprocessing finds the files
            open(p, "wb").close()
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
        parts = list(ex.map(lambda s: pp(a.cc, flags, s), a.srcs))
    last = os.path.join(tmp, "qstr.i.last")
    with open(last, "wb") as f:
        f.write(b"".join(parts))
    mk = [sys.executable, os.path.join(py, "makeqstrdefs.py")]
    for mode, sub in (("qstr", "qstr"), ("module", "module"), ("root_pointer", "root_pointer")):
        d = os.path.join(tmp, sub)
        if os.path.isdir(d):
            for fn in os.listdir(d):
                os.remove(os.path.join(d, fn))
        run(mk + ["split", mode, last, d, "_"])
        run(mk + ["cat", mode, "_", d, os.path.join(tmp, f"{sub}.collected")])
    # qstrdefs: upstream's list + the collected ones, through the preprocessor (config-dependent entries)
    src = open(os.path.join(py, "qstrdefs.h"), "rb").read() + open(os.path.join(tmp, "qstr.collected"), "rb").read()
    src = re.sub(rb"(?m)^(Q\(.*\))", rb'"\1"', src)
    pre = run([a.cc, "-E", "-P"] + flags + ["-x", "c", "-"], input=src)
    pre = re.sub(rb'(?m)^"(Q\(.*\))"', rb"\1", pre)
    prep = os.path.join(tmp, "qstrdefs.preprocessed.h")
    with open(prep, "wb") as f:
        f.write(pre)
    write_if_changed(os.path.join(gen, "qstrdefs.generated.h"),
                     run([sys.executable, os.path.join(py, "makeqstrdata.py"), prep]))
    write_if_changed(os.path.join(gen, "moduledefs.h"),
                     run([sys.executable, os.path.join(py, "makemoduledefs.py"), os.path.join(tmp, "module.collected")]))
    write_if_changed(os.path.join(gen, "root_pointers.h"),
                     run([sys.executable, os.path.join(py, "make_root_pointers.py"),
                          os.path.join(tmp, "root_pointer.collected")]))
    with open(os.path.join(a.out, "stamp"), "w") as f:  # always touched: make compares its time
        f.write("ok\n")


if __name__ == "__main__":
    main()
