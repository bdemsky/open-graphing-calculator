#!/usr/bin/env python3
"""Keyboard documentation generated from keys/layout.py.

    gen_keydoc.py --help-page OUT.txt     help topic "keys" (compiled with the manual by gen_help.py)
    gen_keydoc.py --readme README.md      rewrite the key table between the <!-- keys:begin/end --> markers
    gen_keydoc.py --svg keys/keyboard.svg keyboard map picture (key positions from hardware/gen/layout.py)
    gen_keydoc.py --check                 fail if README.md or keys/keyboard.svg are out of date

keys/layout.py is the single source of truth for what each key does; this
script keeps the three human-readable views of it in sync. The help page is
generated into the build directory by make (and compiled into the manual by
gen_help.py --extra); the README table and the
SVG are checked in, so `make test` runs --check (the keydoc-check target) and
`make keydoc` regenerates them. Every option first runs layout.check()
against hardware/gen/design.py LAYOUT, so a layout that does not match the
PCB fails here too.
"""
import argparse
import ast
import html
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(FW, "keys"))
import layout  # noqa: E402  (keys/layout.py; hardware/gen/layout.py is loaded by path below)

DESIGN = os.path.join(FW, "../hardware/gen/design.py")
README = os.path.join(FW, "README.md")
SVG = os.path.join(FW, "keys/keyboard.svg")
BEGIN, END = "<!-- keys:begin (generated by tools/gen_keydoc.py from keys/layout.py) -->", "<!-- keys:end -->"


def design_layout():
    """LAYOUT (the matrix keys in PCB order, 7 rows of 7) from design.py, read with ast so
    the KiCad generator is not imported."""
    tree = ast.parse(open(DESIGN).read(), DESIGN)
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "LAYOUT" for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit("LAYOUT not found")


def rows():
    """Logical key names row by row, as the keys sit on the keyboard."""
    return layout.rows(design_layout())


def shift_desc(k):
    """SHIFT column text: the SHIFT legend with its description, or just the
    description for keys whose SHIFT function has no printed legend."""
    if k["shift"]:
        return k["shift"] + (f" ({k['shift_doc']})" if k["shift_doc"] else "")
    return k["shift_doc"] or ""


def alpha_desc(k):
    """ALPHA column text: the letter as printed (upper case for ASCII
    letters), "space", or "" if the key has no ALPHA character."""
    a = k["alpha"]
    if a is None:
        return ""
    return {" ": "space", '"': '"', "_": "_ (units)"}.get(a, a.upper() if a.isalpha() and a.isascii() else a)


# ------------------------------------------------------------------ README
def markdown():
    """The README key table (Markdown), one row per key in keyboard order."""
    out =["| Key | Main | SHIFT | ALPHA |", "|---|---|---|---|"]
    for row in rows():
        for name in row:
            k = layout.BY_NAME[name]
            main = k["doc"] or (f"`{k['text']}`" if k["text"] else "")
            if k["text"] and k["doc"]:
                main = f"`{k['text']}` {k['doc']}"
            sh = shift_desc(k)
            if k["shift_text"]:
                sh = f"**{k['shift']}** `{k['shift_text']}{k['shift_suffix'] or ''}`" + \
                     (f" {k['shift_doc']}" if k["shift_doc"] else "")
            elif k["shift"]:
                sh = f"**{k['shift']}**" + (f" {k['shift_doc']}" if k["shift_doc"] else "")
            cells = [f"**{k['legend']}**", main, sh, alpha_desc(k)]
            out.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    return "\n".join(out)


def update_readme(path, check=False):
    """Replace the text between the BEGIN/END markers with markdown().

    With check=True nothing is written and the result says whether the file
    is already up to date; otherwise the file is rewritten only if it changed
    (keeps make's timestamps quiet) and True is returned.
    """
    s = open(path, encoding="utf-8").read()
    a, b = s.index(BEGIN), s.index(END)
    new = s[:a] + BEGIN + "\n" + markdown() + "\n" + s[b:]
    if check:
        return new == s
    if new != s:
        open(path, "w", encoding="utf-8").write(new)
    return True


# ------------------------------------------------------------------ help page
def help_page():
    """Source text (gen_help.py format) of the help topic "keys": intro, a
    fixed-width table of every key, and the global keys."""
    L =["@page keys Keyboard", "# Keyboard", "",
         "Every key has up to three functions: the one on the key, a {shift} function (printed above "
         "the key on the left, blue) and an {alpha} letter (above the key on the right, white). Press "
         "{shift} or {alpha} first, then the key. {alpha} twice gives a capital letter; {shift} {alpha} "
         "locks letters until {alpha} or {clear}.", "",
         "The top row {F1} .. {F5} are soft keys: their labels are at the bottom of the screen and change "
         "with the screen ([[softkeys]]). Tapping a label works too. {shift} {F1} .. {F5} are the "
         "screen's second soft keys (shown while {shift} is pending), {menu} lists them all.", "",
         "## The keys", "",
         "    key    does       SHIFT        ALPHA"]
    for row in rows():
        for name in row:
            k = layout.BY_NAME[name]
            main = k["text"] or (k["action"] or "")
            if k["text"] and k["suffix"]:
                main += k["suffix"]
            sh = k["shift"] or ""
            if not sh and k["shift_doc"]:
                sh = k["shift_doc"]
            al = alpha_desc(k)
            L.append(f"    {k['legend']:<6} {main:<10} {sh:<12} {al}".rstrip())
    L += ["",
          "## Global keys", "",
          "- {home}: the calculator (home or RPN) screen from anywhere; {shift} {home}: settings",
          "- {apps}: all apps; {shift} {apps}: the catalog of every command",
          "- {menu}: options of the current screen; {shift} {menu}: help for it (or for the highlighted "
          "menu item)",
          "- {CAS}, {math}, {vars}: menus that insert commands; {shift} {CAS} constants, "
          "{shift} {math} matrices, {shift} {vars} units",
          "- {⌫} deletes the character before the cursor; {shift} {⌫} switches insert / overwrite",
          "- {clear} clears the line, then leaves the screen; {shift} {clear} also clears the history",
          "- {shift} {▲} / {▼}: backlight; {shift} {◀} / {▶}: start / end of the line",
          "- {shift} {on}: off. {on} stops a long computation.",
          "", "See also [[softkeys]], [[home-screen]], [[index]]."]
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ SVG
def keyboard_svg():
    """SVG picture of the keyboard: one rounded key cap per switch at its PCB
    position (hardware/gen/layout.py key_positions, in mm, scaled by S), cap
    colours from layout.PALETTE by key group, SHIFT legend above the left edge
    and ALPHA legend above the right edge (SHIFT centred if there is no
    ALPHA). Cap sizes are fixed per row type (soft keys, arrows, top rows,
    main block), in mm."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("hwlayout", os.path.join(FW, "../hardware/gen/layout.py"))
    hw = importlib.util.module_from_spec(spec)
    sys.path.append(os.path.join(FW, "../hardware/gen"))  # for its kicad_pcb import
    spec.loader.exec_module(hw)
    pos = hw.key_positions(design_layout())
    S = 6.0  # px per mm
    W, Y0, Y1 = hw.W, hw.ROW_SOFT - 8, hw.ROWS_MAIN[-1] + 8
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W * S:.0f}" height="{(Y1 - Y0) * S:.0f}" '
           f'viewBox="0 {Y0 * S:.1f} {W * S:.1f} {(Y1 - Y0) * S:.1f}" font-family="Helvetica, Arial, sans-serif">',
           f'<rect x="0" y="{Y0 * S:.1f}" width="{W * S:.1f}" height="{(Y1 - Y0) * S:.1f}" rx="18" '
           f'fill="{layout.BODY}"/>']
    for name, (x, y) in pos.items():
        k = layout.BY_NAME[name]
        if name in ("UP", "DOWN"):
            w, h = 8.0, 5.0
        elif name in ("LEFT", "RIGHT"):
            w, h = 5.0, 7.0
        elif y < hw.ROW_A - 5:
            w, h = 12.0, 6.0
        elif y < hw.ROWS_MAIN[0] - 5:
            w, h = 12.6, 7.6
        else:
            w, h = 12.6, 8.4
        c = layout.PALETTE[k["group"]]
        out.append(f'<rect x="{(x - w / 2) * S:.1f}" y="{(y - h / 2) * S:.1f}" width="{w * S:.1f}" '
                   f'height="{h * S:.1f}" rx="5" fill="{c["cap"]}" stroke="#4a4f57" stroke-width="1.5"/>')
        fs = 15 if len(k["legend"]) <= 2 else 12 if len(k["legend"]) <= 4 else 10
        out.append(f'<text x="{x * S:.1f}" y="{y * S + fs * 0.35:.1f}" font-size="{fs}" font-weight="bold" '
                   f'text-anchor="middle" fill="{c["legend"]}">{html.escape(k["legend"])}</text>')
        ty = (y - h / 2 - 0.9) * S
        if k["shift"]:
            anchor, tx = ("start", (x - w / 2) * S) if k["alpha"] else ("middle", x * S)
            out.append(f'<text x="{tx:.1f}" y="{ty:.1f}" font-size="8.5" text-anchor="{anchor}" '
                       f'fill="{layout.SHIFT_INK}">{html.escape(k["shift"])}</text>')
        if k["alpha"]:
            a = alpha_desc(k)
            a = "␣" if a == "space" else a.split()[0]
            out.append(f'<text x="{(x + w / 2) * S:.1f}" y="{ty:.1f}" font-size="8.5" text-anchor="end" '
                       f'fill="{layout.ALPHA_INK}">{html.escape(a)}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


def main():
    """Command line entry; options may be combined (see the module docstring)."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--help-page")
    ap.add_argument("--readme", nargs="?", const=README)
    ap.add_argument("--svg", nargs="?", const=SVG)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    layout.check(design_layout())
    if a.help_page:
        os.makedirs(os.path.dirname(os.path.abspath(a.help_page)), exist_ok=True)
        open(a.help_page, "w", encoding="utf-8").write(help_page())
    if a.readme:
        update_readme(a.readme)
    if a.svg:
        open(a.svg, "w", encoding="utf-8").write(keyboard_svg())
    if a.check:
        bad = []
        if not update_readme(README, check=True):
            bad.append("README.md key table")
        if not os.path.exists(SVG) or open(SVG, encoding="utf-8").read() != keyboard_svg():
            bad.append("keys/keyboard.svg")
        if bad:
            raise SystemExit("out of date (run `make keydoc`): " + ", ".join(bad))
        print("key docs up to date")


if __name__ == "__main__":
    main()
