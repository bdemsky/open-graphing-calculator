/*
 * vdrive — a FAT16 volume generated on the fly for USB mass storage (the
 * "CALC" drive, core/usbdisk.h), and the capture of what a computer writes
 * to it (the way DAPLink, UF2 and micro:bit drives work).
 *
 * Volume (no partition table, 512-byte sectors, one sector per cluster):
 *
 *   sector 0                      boot sector (BPB), generated
 *   1 .. F                        FAT copy 1  \  one buffer (fat[]): generated,
 *   F+1 .. 2F                     FAT copy 2  /  then whatever the host writes
 *   2F+1 .. 2F+R                  root directory (root[]: the same)
 *   data, cluster 2 ...           the free clusters, backed one to one by the
 *                                 staging buffer (stage[]); then the generated
 *                                 files' clusters (read-only, generated by
 *                                 each file's read callback); then the
 *                                 subdirectory's clusters (sub[], like root[]);
 *                                 then padding clusters marked bad when the
 *                                 volume would otherwise be too small for FAT16
 *
 * The free clusters come first: a host that deletes or replaces a generated
 * file frees its clusters, and allocators that search from the low end still
 * put new data into the staging region first (writes to a generated file's
 * clusters are dropped, so a file written there could never be found).
 *
 * One optional subdirectory (vd_add_dir: NOTEBOOKS on the CALC drive) holds
 * files of its own (vd_add_long with dir 1). Generated files may have long
 * names (VFAT entries before an 8.3 entry "NBnnnn~1.EXT"). The subdirectory's
 * entries are generated into sub[] (VD_SUB_SECTORS clusters, one chain); the
 * host may write there, or extend the chain into the staging region when it
 * is full.
 *
 * So the host sees a normal, consistent disk for the whole session: it reads
 * back its own FAT and directory writes, and the data it wrote into free
 * clusters. Nothing written is kept beyond the session: vd_build() (a media
 * change, core/usbdisk.h) generates the volume afresh.
 *
 * Capture. vd_poll() looks, once writes have been quiet for VD_QUIET_MS, at
 * the root directory and the subdirectory as the host wrote them: a file
 * whose directory entry has its size and first cluster, whose FAT chain has
 * exactly the clusters that size needs and ends there, all of them in the
 * staging region and written since the volume was built, is complete. Names
 * starting with '.' (macOS "._NAME" AppleDouble files, .fseventsd,
 * .Spotlight-V100, .Trashes, .DS_Store) and directories (System Volume
 * Information) are never candidates. A found file says whether its name ends
 * in .MOD (a module) or .ipynb (a notebook) and in which directory it is. The
 * order in which a host writes data, FAT and directory does not matter (macOS
 * writes the entry first and its size last, Windows data first): an
 * incomplete file is simply looked at again after the next quiet period.
 * vd_file_read() reads a found file along its chain (it need not be
 * contiguous).
 *
 * Portable C11, no allocation: the caller gives the memory (vd_mem_need),
 * which also holds the table of generated files. Not thread-safe; the USB
 * stack calls it from the main loop.
 */
#ifndef VDRIVE_H
#define VDRIVE_H
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define VD_SECTOR 512u
#define VD_ROOT_ENTRIES 256u   /* 16 sectors: room for the host's metadata files and long names */
#define VD_MIN_CLUSTERS 4200u  /* FAT16 needs at least 4085 clusters; a margin above that */
#define VD_MAX_FILES 80        /* generated files (root and subdirectory) */
#define VD_SUB_SECTORS 32u     /* the subdirectory's generated chain: 512 entries */
#define VD_GEN_CLUSTERS 12288u /* clusters for the generated files and the subdirectory (6 MB) */
#define VD_QUIET_MS 700u       /* writes quiet this long before vd_poll looks */
#define VD_MAX_DONE 8          /* files handled per generation */

enum { VD_ATTR_RO = 0x01, VD_ATTR_HIDDEN = 0x02, VD_ATTR_SYSTEM = 0x04, VD_ATTR_LABEL = 0x08, VD_ATTR_DIR = 0x10,
       VD_ATTR_ARCHIVE = 0x20, VD_ATTR_LFN = 0x0F };

/* A generated file: read(user, off, buf, n) fills n bytes from offset off
 * (n <= VD_SECTOR, never past size). */
typedef struct {
    char name[11];     /* 8.3, blank padded ("INFO    TXT") */
    uint8_t attr;
    uint32_t size;
    void (*read)(void *user, uint32_t off, uint8_t *buf, uint32_t n);
    void *user;
    uint32_t first;    /* first cluster (vd_build) */
    const char *lname; /* long name (ASCII, < 64 characters) or NULL; kept by the caller */
    uint8_t dir;       /* 0 the root, 1 the subdirectory */
} vd_file_t;

/* A file the host wrote (vd_poll). */
typedef struct {
    char name[64];   /* long name if it had one, else NAME.EXT */
    uint32_t first;  /* first cluster */
    uint32_t size;
    bool module;     /* name ends in .MOD */
    bool notebook;   /* name ends in .ipynb */
    uint8_t dir;     /* 0 the root, 1 the subdirectory */
} vd_found_t;

typedef struct {
    /* memory */
    uint8_t *fat, *root, *stage, *written, *sub;
    vd_file_t *files;      /* VD_MAX_FILES entries, in the caller's memory */
    uint32_t stage_clusters;
    /* layout */
    uint32_t fat_sectors, root_sectors, data_start, nclusters, total_sectors;
    uint32_t free_first;   /* first cluster of the staging region (2) */
    uint32_t gen_first;    /* the first cluster after it (the generated files) */
    uint32_t sub_first;    /* the subdirectory's first cluster (0: none) */
    uint32_t pad_first;    /* first bad (padding) cluster */
    uint32_t gen_clusters; /* clusters the generated files take (vd_add_*) */
    char label[11];
    char subname[11];      /* the subdirectory's 8.3 name (subname[0] == 0: none) */
    const char *sublong;   /* and its long name (NULL: none; kept by the caller) */
    uint32_t serial;
    uint16_t date, time;   /* FAT timestamps of the generated entries */
    int nfiles;
    /* host writes */
    bool dirty;            /* written since the last look */
    uint32_t last_write;   /* ms */
    uint32_t writes;       /* sectors written since vd_build */
    vd_found_t done[VD_MAX_DONE];
    int ndone;
    /* sequential vd_file_read cursor */
    uint32_t cur_first, cur_index, cur_cluster;
} vdrive_t;

/* Bytes of memory (FAT, root directory, subdirectory, written bitmap, the
 * file table) for a staging buffer of stage_bytes. */
size_t vd_mem_need(uint32_t stage_bytes);
/* mem: vd_mem_need(stage_bytes) bytes; stage may be NULL (read-only drive). */
void vd_init(vdrive_t *vd, uint8_t *mem, uint8_t *stage, uint32_t stage_bytes);
/* Describe the next generation: label (<= 11 characters), serial, timestamp
 * (FAT format), then vd_add_file / vd_add_dir / vd_add_long for each file,
 * then vd_build. */
void vd_begin(vdrive_t *vd, const char *label, uint32_t serial, uint16_t date, uint16_t time);
int vd_add_file(vdrive_t *vd, const char *name83, uint8_t attr, uint32_t size,
                void (*read)(void *user, uint32_t off, uint8_t *buf, uint32_t n), void *user);
/* The subdirectory, at most one per generation: an 8.3 name, or a long one (kept by the caller;
 * its 8.3 entry is the first six characters and ~1). */
int vd_add_dir(vdrive_t *vd, const char *name);
/* A file with a long name in the root (dir 0) or the subdirectory (dir 1;
 * vd_add_dir first). -1: the table or the clusters for generated files are
 * full. */
int vd_add_long(vdrive_t *vd, int dir, const char *lname, uint8_t attr, uint32_t size,
                void (*read)(void *user, uint32_t off, uint8_t *buf, uint32_t n), void *user);
void vd_build(vdrive_t *vd);
uint32_t vd_sectors(const vdrive_t *vd);
bool vd_writable(const vdrive_t *vd);
uint32_t vd_free_bytes(const vdrive_t *vd);   /* what the host can store (the staging region) */

/* One sector (lba < vd_sectors). */
void vd_read(vdrive_t *vd, uint32_t lba, uint8_t *buf);
void vd_write(vdrive_t *vd, uint32_t lba, const uint8_t *buf, uint32_t now);

/* After VD_QUIET_MS without writes: the next complete file not handled yet
 * (1, *f filled), else 0. Hand each file back with vd_done (or it is found
 * again). */
int vd_poll(vdrive_t *vd, uint32_t now, vd_found_t *f);
void vd_done(vdrive_t *vd, const vd_found_t *f);
/* n bytes of a found file at off (along its chain); bytes read, <0 if the
 * chain left the staging region. */
int vd_file_read(vdrive_t *vd, const vd_found_t *f, uint32_t off, void *buf, uint32_t n);
/* 8.3 directory name "INFO    TXT" from "INFO.TXT" (upper case); false if it does not fit */
bool vd_name83(const char *name, char out[11]);

#endif
