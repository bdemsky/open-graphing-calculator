/* the finales won and places visited (worlds 0-7 in bosses / visited, 8.. in pad[1] / pad[2]) */
static inline bool mq_boss_won(const mq_profile_t *p, int w)
{
    return w < 8 ? (p->bosses >> w) & 1 : (p->pad[1] >> (w - 8)) & 1;
}
static inline void mq_boss_set(mq_profile_t *p, int w)
{
    if (w < 8)
        p->bosses = (uint8_t)(p->bosses | 1 << w);
    else
        p->pad[1] = (uint8_t)(p->pad[1] | 1 << (w - 8));
}
static inline void mq_visit_set(mq_profile_t *p, int w)
{
    if (w < 8)
        p->visited = (uint8_t)(p->visited | 1 << w);
    else
        p->pad[2] = (uint8_t)(p->pad[2] | 1 << (w - 8));
}
