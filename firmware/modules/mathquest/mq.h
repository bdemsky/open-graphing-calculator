/*
 * Math Quest code module ("mathquest", interface modx ABI 1): shared types.
 *
 * Educational math games for grades 3 and 4 (design: docs/MATHQUEST.md).
 * Files:
 *   mq_main.c    module entry, scenes (title, map, worlds, play, feedback,
 *                worked examples, celebrations, room, stickers, parent screen),
 *                buttons / focus / input, console `mq`, state keys
 *   mq_curric.c  the curriculum: standards table (CCSS grades 3 and 4, grade-2
 *                foundations, grade-5 challenge, each with its Star Math domain),
 *                skills, worlds and levels, misconceptions
 *   mq_gen.c     problem generators (answers, known wrong answers with their
 *                misconception), answer parsing and checking, the classifier
 *   mq_steps.c   worked examples ("show me how") for every skill
 *   mq_facts.c   multiplication / division facts: Leitner boxes, fluency,
 *                fact families, strategies, the four fact games
 *   mq_vis.c     drawing: primitives, sprites, visual models (arrays, fraction
 *                bars and pies, base-ten blocks, number lines, clocks, grids,
 *                angles, shapes, coins, graphs, line plots, tables, ...)
 *   mq_theme.c   theme packs (.THM) from /CALC/THEMES on the microSD card
 *   mq_art.c     the built-in cast and stickers (generated by tools/gen_mq_art.py)
 *
 * Image rules (it runs in place from the QSPI): no static RW data (all state
 * is in mq_t, the RW block the core allocates and zeroes at bind), no library
 * calls (only the API table q->api), no pointers in constant tables (tables
 * hold characters and numbers). Integer arithmetic only (32-bit; no 64-bit
 * division, no libm), so the native and WebAssembly simulators draw the same
 * pixels.
 *
 * Persistence: mq_save_t (2 profiles, about 24 KB) is copied to the core with
 * api->save_put after every change and read back with api->save_get at bind;
 * the core keeps it in the session blob "modx.save" (app/modx.c).
 */
