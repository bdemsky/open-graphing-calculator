/* A time mark (B2, CR2-05): "now" on the animation clock, never 0 (0 means "none") and never in the future (the old
 * `anim_t | 1` was anim_t + 1 on an even tick, and "within N ms of it" read as 4 billion ms in that same tick).
 * mq_since reads a mark signed, so even a stray future mark reads as "just now". `make test` (mq-mark-check) keeps
 * new `| 1` marks out. */
static inline uint32_t mq_mark(const mq_t *q) { return q->anim_t ? q->anim_t : 1u; }
static inline uint32_t mq_mark_now(const mq_t *q) { return q->now ? q->now : 1u; }
static inline int32_t mq_since(const mq_t *q, uint32_t mark) { return (int32_t)(q->anim_t - mark); }
/* B9 (CR2-20): a saved count that only grows holds at its top instead of wrapping to 0 */
static inline uint16_t mq_sat16(uint32_t v) { return (uint16_t)(v > 65535u ? 65535u : v); }

