/* ------------------------------------------------------------------ shop */
static bool in_tab(int id, int tab)
{
    switch (IT(id)->cat) {
    case HC_FURN: case HC_LIGHT: case HC_RUG: case HC_PLANT: return tab == 0;
    case HC_WALLDECO: case HC_TOY: return tab == 1;
    case HC_PET: return tab == 2;
    case HC_WALL: case HC_FLOOR: return tab == 3;
    case HC_WINDOW: return tab == 4;
    case HC_OUTFIT: return tab == 5;
    default: return false;
    }
}

/* the k-th item of a shop tab: the ones on sale first, then those still locked */
static int shop_item(mq_t *q, int tab, int k, int *count)
{
    int n = 0, found = 0;
    for (int pass = 0; pass < 2; pass++)
        for (int id = 1; id <= MQ_NITEM; id++) {
            const mq_item_t *t = IT(id);
            if (!t->price || (t->flags & (F_GIFT | F_SPECIAL | F_RETIRED)) || !in_tab(id, tab))
                continue;
            if (sold_now(q, id) != (pass == 0))
                continue;
            if (n == k)
                found = id;
            n++;
        }
    if (count)
        *count = n;
    return found;
}

/* an item's picture fitted into a w x h box (centred) */
static void item_fit(mq_t *q, int id, int x, int y, int w, int h, int sil)
{
    const mq_item_t *t = IT(id);
    if (is_style(id)) {
        if (sil >= 0)
            mq_rrect(q, x + 2, y + 2, w - 4, h - 4, 4, (uint16_t)sil);
        else
            pattern(q, id, x + 2, y + 2, w - 4, h - 4, 0);
        return;
    }
    int aw = t->cat == HC_STICKER ? 16 : t->aw, ah = t->cat == HC_STICKER ? 16 : t->ah;
    if (!aw || !ah)
        return;
    int s = imin(imin(w / aw, h / ah), 3); /* 0: half size */
    if (t->cat == HC_OUTFIT) /* on a little ghost buddy shape */
        mq_circle(q, x + w / 2, y + h / 2 + 2, imin(w, h) / 3, sil >= 0 ? Q_GREY : RGB(240, 236, 248));
    int dw = s ? aw * s : aw / 2, dh = s ? ah * s : ah / 2;
    mq_item_draw(q, id, x + (w - dw) / 2, y + (h - dh) / 2, 0, frame_of(q, id), s, sil);
}

