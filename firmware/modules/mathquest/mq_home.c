void mq_home_press(mq_t *q, int id, int arg)
{
    mq_profile_t *p = mq_prof(q);
    int r = q->hm_room;
    switch (id) {
    case HB_TAB: q->shop_tab = (uint8_t)arg, q->shop_page = 0, q->shop_pick = 0; break;
    case HB_PAGE: {
        int count;
        shop_item(q, q->shop_tab, 0, &count);
        int pages = (count + SHOP_N - 1) / SHOP_N;
        int np = q->shop_page + (arg ? 1 : -1);
        if (np < 0 || np >= pages) /* the first or the last page: a gentle bump, never round (nor back) */
            mq_sfx(q, MODX_SFX_TAP, 0), q->page_bump_t = mq_mark(q), q->page_bump = (uint8_t)arg;
        else
            q->shop_page = (uint8_t)np;
        break;
    }
    case HB_CARD: q->shop_pick = (uint8_t)arg, q->new_set = 0xFF; break;
    case HB_CLOSE: q->shop_pick = 0; break;
    case HB_BUY: {
        if (q->scene == SC_WARDROBE && mq_buy_check(q, arg) == -3) /* (the card says how much more) */
            break;
        if (!mq_buy_check(q, arg) && mq_pay_mode(q, IT(arg)->price) != PM_TAP) { /* paid with coins at the counter */
            mq_pay_open(q, arg);
            break;
        }
        int e = mq_buy(q, arg);
        if (!e) {
            mq_spark_burst(q, 90, MQ_Y0 + 90, 20);
            q->api->snprintf(q->toast_in, sizeof q->toast_in, "You got a %s!", IT(arg)->name);
            mq_toast(q, q->toast_in);
            if (q->new_bonus)
                mq_toast(q, "Set complete! A bonus prize!"); /* (in the lane, after it: not the core's toast over the shop) */
            q->new_bonus = 0;
            mq_keep(q); /* (a purchase: kept at once) */
        } else
            mq_toast(q, e == -3 ? "Not enough coins yet!" : e == -4 ? "You have that one!"
                      : IT(arg)->cat == HC_OUTFIT ? "New clothes come each day!" : "Not yet!");
        break;
    }
    case HB_PLACEIT:
        q->shop_pick = 0;
        if (is_style(arg)) {
            mq_home_enter(q, SC_ROOM);
            mq_set_style(q, q->hm_room, arg);
        } else {
            mq_home_enter(q, SC_ROOM);
            int x, y;
            default_spot(q, arg, &x, &y);
            select_item(q, mq_place(q, q->hm_room, arg, x, y, 0));
        }
        break;
    case HB_WEAR:
        if (arg > 200) { /* a boss hat */
            mq_home(q)->wear[OS_HEAD] = 0;
            p->hat = (uint8_t)(p->hat == arg - 200 ? 0 : arg - 200);
            q->dirty = true;
        } else
            mq_wear(q, arg);
        if (q->scene == SC_SHOP)
            mq_home_enter(q, SC_WARDROBE);
        else
            q->shop_pick = 0; /* (a rack piece up close: put on, the card closes) */
        break;
    case HB_STORY: mq_hstory_press(q, arg); break; /* the friend's card: "go see!" or "later" (mq_homestory.c) */
    case HB_WRPAGE: {
        int count;
        wr_item(q, 0, &count);
        int pages = (count + WR_PER - 1) / WR_PER, np = q->wr_page + (arg ? 1 : -1);
        if (np < 0 || np >= pages)
            mq_sfx(q, MODX_SFX_TAP, 0);
        else
            q->wr_page = (uint8_t)np;
        break;
    }
    case HB_TRAYPAGE:
        if (arg && (q->hm_tray + 1) * TRAY_N < mq_home_tray_count(q)) /* (never past the last page: CR-14) */
            q->hm_tray++;
        else if (arg)
            mq_sfx(q, MODX_SFX_TAP, 0);
        else if (q->hm_tray)
            q->hm_tray--;
        break;
    case HB_TRAY:
        if (is_style(arg))
            mq_set_style(q, r, arg);
        else {
            int x, y;
            default_spot(q, arg, &x, &y);
            select_item(q, mq_place(q, r, arg, x, y, 0));
        }
        break;
    case HB_TOOL: {
        int k = q->hm_sel;
        if (arg == 0 || arg == 1)
            mq_turn(q, r, k, arg == 1);
        else if (arg == 2 || arg == 3)
            q->hm_sel = (int8_t)mq_layer(q, r, k, arg == 2 ? 1 : -1);
        else if (arg == 4) {
            mq_remove(q, r, k);
            q->hm_sel = -1;
        } else
            q->hm_sel = -1;
        break;
    }
    case HB_BOOKSET:
        if ((arg && q->book_set >= 10) || (!arg && q->book_set == 0))
            mq_sfx(q, MODX_SFX_TAP, 0), q->page_bump_t = mq_mark(q), q->page_bump = (uint8_t)arg;
        else
            q->book_set = (uint8_t)(q->book_set + (arg ? 1 : -1));
        q->book_pick = 0;
        break;
    case HB_BOOKITEM: q->book_pick = (uint8_t)(q->book_pick == arg ? 0 : arg); break;
    default: break;
    }
    q->redraw = true;
}

/* the placed item under (x, y), topmost first; -1 */
static int hit_item(mq_t *q, int x, int y)
{
    mq_room_t *rm = room(q, q->hm_room);
    for (int k = rm->n - 1; k >= 0; k--) {
        int ix, iy, w, h;
        item_box(q, &rm->it[k], RY, &ix, &iy, &w, &h);
        if (x >= ix && x < ix + w && y >= iy && y < iy + h)
            return k;
    }
    return -1;
}

static void drag_cell(mq_t *q, int x, int y)
{
    int gx = (x - q->hm_offx - RX + HM_CELL / 2) / HM_CELL, gy = (y - q->hm_offy - RY + HM_CELL / 2) / HM_CELL;
    if (x - q->hm_offx - RX + HM_CELL / 2 < 0)
        gx = 0;
    if (y - q->hm_offy - RY + HM_CELL / 2 < 0)
        gy = 0;
    clamp_pos(q->hm_drag_id, q->hm_drag_fl, &gx, &gy);
    q->hm_gx = (int8_t)gx, q->hm_gy = (int8_t)gy;
}

/* touch in the room: drag and drop (down, drag, up); taps on items select them.
 * -> true if used (taps on buttons are left to the caller) */
bool mq_home_touch(mq_t *q, int type, int x, int y)
{
    if ((q->scene == SC_SHOP || q->scene == SC_WARDROBE) && mq_pay_on(q)) /* the counter takes every touch */
        return mq_pay_touch(q, type, x, y);
    if (mq_hstory_touch(q, type, x, y)) /* the friend's card: its buttons take the tap, the room under it nothing */
        return type != TV_TAP;
    if (q->scene == SC_WARDROBE && q->shop_pick && type == TV_TAP &&
        (x < WC_X || x >= WC_X + WC_W || y < WC_Y || y >= WC_Y + WC_H)) { /* beside the piece's card: it closes */
        q->shop_pick = 0, q->redraw = true;
        return true;
    }
    if (q->scene == SC_SHOP && q->shop_pick && type == TV_TAP &&
        (x < 20 || x >= 300 || y < MQ_Y0 + 30 || y >= MQ_Y0 + 190)) { /* a tap beside the item card closes it (the
                                                                    * bot's 11: the shop round it looked live) */
        q->shop_pick = 0, q->redraw = true;
        return true;
    }
    if (q->scene != SC_ROOM)
        return false;
    bool in_room = y >= RY && y < RY + RH;
    switch (type) {
    case TV_DOWN: {
        q->hm_fx = (int16_t)x, q->hm_fy = (int16_t)y, q->hm_moved = false;
        q->hm_sel0 = (int8_t)(q->hm_sel + 2); /* (what was selected before this finger: its TAP toggles that) */
        int k = in_room ? hit_item(q, x, y) : -1;
        if (k >= 0) {
            const mq_place_t *t = &room(q, q->hm_room)->it[k];
            q->hm_drag = 1, q->hm_sel = (int8_t)k, q->hm_drag_id = t->id, q->hm_drag_fl = t->fl;
            q->hm_offx = (int16_t)(x - RX - t->x * HM_CELL), q->hm_offy = (int16_t)(y - RY - t->y * HM_CELL);
            q->hm_gx = (int8_t)t->x, q->hm_gy = (int8_t)t->y;
            return true;
        }
        for (int i = 0; i < q->nbtn; i++) { /* a tray card: drag a new item out */
            const mq_btn_t *b = &q->btn[i];
            if (b->id == HB_TRAY && !is_style(b->arg) && x >= b->x && x < b->x + b->w && y >= b->y && y < b->y + b->h) {
                q->hm_drag = 2, q->hm_drag_id = b->arg, q->hm_drag_fl = 0;
                q->hm_offx = (int16_t)(foot_w(b->arg) * HM_CELL / 2), q->hm_offy = (int16_t)(foot_h(b->arg) * HM_CELL / 2);
                return true;
            }
        }
        q->hm_drag = 0;
        return false;
    }
    case TV_DRAG:
        if (!q->hm_drag)
            return false;
        q->hm_fx = (int16_t)x, q->hm_fy = (int16_t)y, q->hm_moved = true;
        drag_cell(q, x, y);
        q->redraw = true;
        return true;
    case TV_UP: {
        int d = q->hm_drag;
        q->hm_drag = 0;
        q->redraw = true;
        if (d == 1 && q->hm_moved) {
            drag_cell(q, x, y);
            mq_move(q, q->hm_room, q->hm_sel, q->hm_gx, q->hm_gy);
            return true;
        }
        if (d == 2 && q->hm_moved && in_room) {
            drag_cell(q, x, y);
            select_item(q, mq_place(q, q->hm_room, q->hm_drag_id, q->hm_gx, q->hm_gy, 0));
            return true;
        }
        return d != 0;
    }
    case TV_CANCEL:
        q->hm_drag = 0;
        q->redraw = true;
        return true;
    case TV_TAP: {
        q->hm_drag = 0;
        int before = q->hm_sel0 ? q->hm_sel0 - 2 : q->hm_sel; /* (the DOWN selected it to drag: a tap selects it, a
                                                              * second tap on it puts it down -- CR2-02) */
        q->hm_sel0 = 0;
        if (!in_room)
            return false;
        int k = hit_item(q, x, y);
        select_item(q, k == before ? -1 : k);
        return true;
    }
    default: return false;
    }
}

/* swipes in the home scenes (dir 0 left, 1 right, 2 up, 3 down): rooms, shop pages, book
 * pages; a swipe that began on a room item moved the item instead. -> true if used */
bool mq_home_swipe(mq_t *q, int dir, int x0, int y0)
{
    if (dir > 1)
        return false;
    switch (q->scene) {
    case SC_ROOM:
        if (q->hm_moved) /* the gesture dragged an item */
            return true;
        if (dir == 0)
            next_room(q);
        else { /* the previous open room: once round the open ones, less one */
            int open = 0;
            for (int r = 0; r < HM_NROOM; r++)
                open += mq_room_open(mq_prof(q), r);
            for (int k = 0; k < open - 1; k++)
                next_room(q);
        }
        return true;
    case SC_SHOP:
        if (!q->shop_pick && !mq_pay_on(q))
            mq_home_press(q, HB_PAGE, dir == 0);
        return true;
    case SC_BOOK: mq_home_press(q, HB_BOOKSET, dir == 0); return true;
    case SC_WARDROBE: /* her things' pages (not while a piece is up close or paying) */
        if (!q->shop_pick && !mq_pay_on(q))
            mq_home_press(q, HB_WRPAGE, dir == 0);
        return true;
    case SC_SHOWOFF:
        if (dir == 0)
            next_room(q);
        return true;
    default: return false;
    }
}

/* keys in the home scenes: arrows move the selected item, DEL puts it away */
bool mq_home_key(mq_t *q, int k)
{
    if ((q->scene == SC_SHOP || q->scene == SC_WARDROBE) && mq_pay_on(q))
        return mq_pay_key(q, k, q->api->key_char ? q->api->key_char(k, 0) : 0);
    if (q->scene == SC_ROOM && q->hm_sel >= 0) {
        mq_room_t *rm = room(q, q->hm_room);
        if (q->hm_sel >= rm->n)
            return false;
        mq_place_t *t = &rm->it[q->hm_sel];
        int dx = k == HK_LEFT ? -1 : k == HK_RIGHT ? 1 : 0, dy = k == HK_UP ? -1 : k == HK_DOWN ? 1 : 0;
        if (dx || dy) {
            mq_move(q, q->hm_room, q->hm_sel, t->x + dx, t->y + dy);
            q->redraw = true;
            return true;
        }
        if (k == HK_DEL) {
            mq_remove(q, q->hm_room, q->hm_sel);
            q->hm_sel = -1;
            q->redraw = true;
            return true;
        }
    }
    if (q->scene == SC_SHOP && q->shop_pick && (k == HK_DEL || k == HK_LEFT || k == HK_RIGHT)) { /* (the card away; the arrows
                                                                                              * then page) */
        q->shop_pick = 0;
        q->redraw = true;
        return true;
    }
    /* paged screens: LEFT / RIGHT turn the page (a bump at the ends), never back (the playtest: in the
     * shop LEFT went back); UP / DOWN still move between the buttons */
    if ((q->scene == SC_SHOP && !q->shop_pick) || q->scene == SC_BOOK) {
        if (k == HK_LEFT || k == HK_RIGHT) {
            mq_home_press(q, q->scene == SC_SHOP ? HB_PAGE : HB_BOOKSET, k == HK_RIGHT);
            q->redraw = true;
            return true;
        }
    }
    return false;
}

/* ------------------------------------------------------------------ animation */
static void walker_step(mq_t *q, int i)
{
    mq_room_t *rm = room(q, q->hm_room);
    if (q->now < q->wk_until[i] && !(i == 0 && q->out_t))
        return;
    bool was_story = q->wk_react[i] >= 51;
    if (q->wk_react[i] && q->now >= q->wk_until[i])
        q->wk_react[i] = 0;
    int sx = i == 0 ? mq_hstory_walk_x(q) : -1; /* the home story: restless, at the window; off to the door */
    if (sx >= 0) {
        q->wk_item[i] = 0;
        sx = imax(0, imin(RW - 40, sx));
        q->wk_tx[i] = (int16_t)sx;
        if (q->wk_x[i] == sx && !q->out_t) {
            if (was_story)
                q->wk_until[i] = q->now + 700; /* a breath, then she looks out again */
            else
                q->wk_react[i] = (uint8_t)(51 + mq_hstory_icon(q)), q->wk_until[i] = q->now + 1600;
            return;
        }
        if (q->out_t)
            q->wk_react[i] = 0;
    }
    int x = q->wk_x[i], tx = q->wk_tx[i];
    if (x != tx) {
        int st = tx > x ? 1 : -1;
        q->wk_x[i] = (int16_t)(x + st * (i ? 1 : q->out_t ? 4 : 2));
        if ((st > 0 && q->wk_x[i] > tx) || (st < 0 && q->wk_x[i] < tx))
            q->wk_x[i] = (int16_t)tx;
        q->wk_face[i] = (uint8_t)(st > 0);
        return;
    }
    if (q->wk_item[i]) { /* arrived at a thing: react to it */
        q->wk_react[i] = (uint8_t)(IT(q->wk_item[i])->react + 1);
        q->wk_until[i] = q->now + 1600;
        q->wk_item[i] = 0;
        return;
    }
    /* pick somewhere new: usually something in the room */
    if (rm->n && mq_rnd(q, 0, 4)) {
        const mq_place_t *t = &rm->it[mq_rnd(q, 0, rm->n - 1)];
        int w, h;
        footprint(t->id, t->fl, &w, &h);
        q->wk_tx[i] = (int16_t)imax(0, imin(RW - 40, t->x * HM_CELL + w * HM_CELL / 2 - 20 + (i ? 12 : -12)));
        q->wk_item[i] = t->id;
    } else
        q->wk_tx[i] = (int16_t)mq_rnd(q, 0, RW - 40);
    q->wk_until[i] = q->now + (uint32_t)mq_rnd(q, 200, 900);
}

void mq_home_frame(mq_t *q, uint32_t dt)
{
    (void)dt;
    if (q->scene == SC_ROOM || q->scene == SC_SHOWOFF) {
        walker_step(q, 0);
        walker_step(q, 1);
        if (q->scene == SC_SHOWOFF && q->anim_t % 400 < 40) /* sparkles keep coming */
            mq_spark_burst(q, mq_rnd(q, 20, 300), mq_rnd(q, MQ_Y0 + 40, MQ_Y0 + 160), 3);
    }
    if (q->scene == SC_SHOP || q->scene == SC_WARDROBE)
        mq_pay_frame(q);
}

bool mq_home_animating(mq_t *q)
{
    if (q->scene == SC_ROOM || q->scene == SC_SHOWOFF)
        return true; /* walkers, pets */
    if ((q->scene == SC_SHOP || q->scene == SC_WARDROBE) && mq_pay_animating(q))
        return true;
    if (q->scene == SC_WARDROBE && mq_hstory_stage(q) >= 1) /* (the buddy's thought, the friend's card) */
        return true;
    return (q->anim_t / 125) % 4 == 0 || (q->pop_coins && q->now - q->pop_t < 1600u);
}

/* ------------------------------------------------------------------ console and state */
static int lookup(mq_t *q, const char *s)
{
    long v;
    if (q->api->con_parse_int(s, &v))
        return v >= 1 && v <= MQ_NITEM ? (int)v : 0;
    for (int id = 1; id <= MQ_NITEM; id++) { /* by name, '_' for spaces, any case */
        const char *a = mq_item[id].name, *b = s;
        while (*a && *b) {
            char ca = *a >= 'A' && *a <= 'Z' ? (char)(*a + 32) : *a, cb = *b == '_' ? ' ' : *b;
            cb = cb >= 'A' && cb <= 'Z' ? (char)(cb + 32) : cb;
            if (ca != cb)
                break;
            a++, b++;
        }
        if (!*a && !*b)
            return id;
    }
    return 0;
}

/* mq coins N | buy ITEM | place ITEM X Y [FL] | room N | sel K | turn | flip | front | back | store | undo |
 * style ITEM | wear ITEM | gift | photo | drag X0 Y0 X1 Y1 | catalog;  -> -2 if not a home command */
int mq_home_console(mq_t *q, int argc, char **argv)
{
    const modx_api_t *api = q->api;
    const char *sub = argv[1];
    long n = 0, m = 0, f = 0;
    int r = q->hm_room;
#define IS(s) (!api->strcmp(sub, s))
    if (IS("pay") || IS("purse"))
        return mq_purse_console(q, argc, argv);
    if (IS("coins") && argc > 2 && api->con_parse_int(argv[2], &n)) { /* (cents in her purse) */
        mq_purse_set(q, (uint32_t)(n < 0 ? 0 : n > HM_COINS_MAX ? HM_COINS_MAX : n));
    } else if (IS("buy") && argc > 2) {
        int id = lookup(q, argv[2]), e = mq_buy(q, id);
        if (e)
            return api->con_error("cannot buy %s (%d)", argc > 2 ? argv[2] : "", e);
    } else if (IS("place") && argc > 4 && api->con_parse_int(argv[3], &n) && api->con_parse_int(argv[4], &m)) {
        if (argc > 5)
            api->con_parse_int(argv[5], &f);
        int k = mq_place(q, r, lookup(q, argv[2]), (int)n, (int)m, (int)f);
        if (k < 0)
            return api->con_error("cannot place %s", argv[2]);
        q->hm_sel = (int8_t)k;
    } else if (IS("room") && argc > 2 && api->con_parse_int(argv[2], &n)) {
        if (!mq_room_open(mq_prof(q), (int)n))
            return api->con_error("room %ld is locked", n);
        mq_home(q)->room_cur = (uint8_t)n;
        if (q->scene != SC_ROOM && q->scene != SC_SHOWOFF)
            mq_home_enter(q, SC_ROOM);
        q->hm_room = (uint8_t)n, q->hm_sel = -1, q->hm_nundo = 0;
    } else if (IS("sel") && argc > 2 && api->con_parse_int(argv[2], &n)) {
        q->hm_sel = (int8_t)(n >= 0 && n < room(q, r)->n ? n : -1);
    } else if (IS("turn") || IS("flip")) {
        mq_turn(q, r, q->hm_sel, IS("flip"));
    } else if (IS("front") || IS("back")) {
        q->hm_sel = (int8_t)mq_layer(q, r, q->hm_sel, IS("front") ? 1 : -1);
    } else if (IS("store")) {
        mq_remove(q, r, q->hm_sel);
        q->hm_sel = -1;
    } else if (IS("undo")) {
        if (!mq_undo(q))
            return api->con_error("nothing to undo");
    } else if (IS("style") && argc > 2) {
        if (mq_set_style(q, r, lookup(q, argv[2])))
            return api->con_error("no such style owned");
    } else if (IS("wear") && argc > 2) {
        if (mq_wear(q, lookup(q, argv[2])))
            return api->con_error("no such outfit owned");
    } else if (IS("gift")) {
        mq_open_gift(q);
    } else if (IS("photo")) {
        photo(q);
    } else if (IS("catalog")) {
        for (int id = 1; id <= MQ_NITEM; id++)
            api->con_printf("%d %s %s %d %d\n", id, mq_item[id].name, set_name[mq_item[id].set % HM_NSET],
                            mq_item[id].price, mq_item_owned(q, id));
    } else
        return -2;
#undef IS
    q->redraw = true;
    return 0;
}

void mq_home_state(mq_t *q, void (*kv)(const char *, const char *, void *), void *user)
{
    const modx_api_t *api = q->api;
    mq_home_t *h = mq_home(q);
    char b[48];
    mq_purse_state(q, kv, user); /* mq_coins (cents), the purse, the counter */
    api->snprintf(b, sizeof b, "%lu", (unsigned long)h->earned);
    kv("mq_earned", b, user);
    kv("mq_room", room_name[q->hm_room % HM_NROOM], user);
    mq_room_t *rm = room(q, q->hm_room);
    api->snprintf(b, sizeof b, "%d", rm->n);
    kv("mq_placed", b, user);
    api->snprintf(b, sizeof b, "%d", q->hm_sel);
    kv("mq_sel", b, user);
    if (q->hm_sel >= 0 && q->hm_sel < rm->n) {
        const mq_place_t *t = &rm->it[q->hm_sel];
        api->snprintf(b, sizeof b, "%s %d,%d %d", IT(t->id)->name, t->x, t->y, t->fl);
    } else
        b[0] = 0;
    kv("mq_sel_item", b, user);
    int found = 0, all = 0;
    for (int id = 1; id <= MQ_NITEM; id++) {
        int o = mq_item_owned(q, id);

        if (!(IT(id)->flags & F_RETIRED) && !(is_style(id) && !IT(id)->price && !(IT(id)->flags & F_SPECIAL)))
            all++, found += o > 0;
    }
    api->snprintf(b, sizeof b, "%d/%d", found, all);
    kv("mq_found", b, user);
    api->snprintf(b, sizeof b, "%d", h->bonus);
    kv("mq_sets", b, user);
    api->snprintf(b, sizeof b, "%d %d %d %d %d", h->wear[0], h->wear[1], h->wear[2], h->wear[3], h->wear[4]);
    kv("mq_wear", b, user);
    mq_rack_fill(q);
    api->snprintf(b, sizeof b, "%d %d %d", h->rack[0], h->rack[1], h->rack[2]); /* today's clothes rack */
    kv("mq_rack", b, user);
    kv("mq_shot", q->shot_msg, user);
    kv("mq_earn_msg", q->earn_msg, user);
    api->snprintf(b, sizeof b, "%d", q->scene == SC_BOOK ? q->book_set : q->shop_page);
    kv("mq_page", b, user);
}
