        mq_home_t *h = mq_home(q);
        q->hm_room = (uint8_t)(mq_room_open(mq_prof(q), h->room_cur) ? h->room_cur : 0);
        q->hm_sel = -1, q->hm_drag = 0, q->hm_nundo = 0, q->hm_tray = 0;
