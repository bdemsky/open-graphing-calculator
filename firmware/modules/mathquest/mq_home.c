/*
 * Math Quest: the home. Coins, the shop, rooms to decorate, outfits, the
 * catalogue book and set bonuses (design: docs/MATHQUEST.md, "Home").
 *
 * Economy. Coins are earned only by learning: right answers (3 on a skill that
 * is still being learned, 1 on a mastered one; a mastered skill played more
 * than 8 times pays only every third answer), bouncing back after a mistake
 * (the similar problem right: +2), combos of 5, finishing a worked example
 * (+2 once per level run), mastering a skill (+25), a fact becoming fluent
 * (+5), finishing a level (+10 the first time, +5 the first three-star
 * finish), beating a boss (+50 the first time), completing a set (+20) and the
 * daily gift. Grinding mastered material pays little; milestones pay a lot.
 *
 * Items (mq_items.c, generated by tools/gen_mq_items.py) are bought with
 * coins; a world's themed set appears in the shop when that world opens.
 * Owning every item of a world set gives its bonus item. The rooms (bedroom,
 * garden, cafe, treehouse, castle tower) open with the worlds too. A room is
 * a 20 x 9 grid of 16-pixel cells (5 rows of wall, 4 of floor); placed items
 * are drawn in order (later = in front), can be dragged, turned, mirrored,
 * moved to the front or back, put away (back to the tray) and every change can
 * be undone. The buddy and a friend wander about and react to the things they
 * walk up to; pets and some decorations animate. Show-off mode shows the room
 * full screen with sparkles and saves a screenshot to the card.
 *
 * All state is in mq_t (RW block) and mq_home_t (saved per profile).
 */
